// Bytes ↔ base64, for embedding files in a project.

// Base64 <-> ArrayBuffer, for embedding a source PDF's raw bytes inside
// a saved project's JSON. Chunked to avoid blowing the call stack that
// spreading a huge byte array into String.fromCharCode would risk.
export function arrayBufferToBase64(buf) {
  const bytes = new Uint8Array(buf);
  const chunkSize = 0x8000;
  let binary = "";
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}

export function base64ToArrayBuffer(b64) {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes.buffer;
}
